  function group(n) { return String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ','); }
  KTA.fmt = {
    num: function (v, d) {
      if (!isNum(v)) return '-';
      var s = v.toFixed(d == null ? 0 : d);
      var parts = s.split('.');
      parts[0] = parts[0].replace('-', '');
      return (v < 0 && +s !== 0 ? '-' : '') + group(parts[0]) + (parts[1] ? '.' + parts[1] : '');
    },
    signed: function (v, d, unit) {
      if (!isNum(v)) return '-';
      var s = KTA.fmt.num(Math.abs(v), d == null ? 1 : d);
      return (v > 0 ? '+' : (v < 0 ? '-' : '')) + s + (unit || '');
    },
    afr: function (lambda) { return isNum(lambda) ? (lambda * GAS).toFixed(1) : '-'; },
    lambda: function (lambda) { return isNum(lambda) ? lambda.toFixed(2) : '-'; },
    afrLambda: function (lambda) {
      return isNum(lambda) ? (lambda * GAS).toFixed(1) + ' AFR (λ ' + lambda.toFixed(2) + ')' : '-';
    },
    hz: function (hz) { return isNum(hz) ? group(Math.round(hz)) + ' Hz' : '-'; }
  };

