  function refBoostAt(rpm) {
    var ax = REF.boost.rpm, rows = REF.boost.normal;
    var peak = rows.map(function (r) { return Math.max.apply(null, r); });
    return interp1(ax, peak, rpm);
  }
  KTA.refBoostAt = refBoostAt;

  function binByAxis(axis, xs, vals, mask) {
    var m = axis.length, sum = new Float64Array(m), w = new Float64Array(m);
    for (var i = 0; i < xs.length; i++) {
      if (mask && !mask[i]) continue;
      var x = xs[i], v = vals[i];
      if (!isNum(x) || !isNum(v)) continue;
      var p = locate(axis, x);
      var wa = 1 - p.f;
      sum[p.i] += wa * v; w[p.i] += wa;
      if (p.f > 0 && p.i + 1 < m) { sum[p.i + 1] += p.f * v; w[p.i + 1] += p.f; }
    }
    var out = [];
    for (var k = 0; k < m; k++) out.push({ hz: axis[k], weight: round(w[k], 2), mean: w[k] > 0 ? sum[k] / w[k] : NaN });
    return out;
  }

  function grade(v, lim, lowerIsWorse) {
    if (!isNum(v)) return 'nodata';
    if (lowerIsWorse) return v >= lim.good ? 'good' : (v >= lim.watch ? 'watch' : 'stop');
    return v <= lim.good ? 'good' : (v <= lim.watch ? 'watch' : 'stop');
  }
  function worst(list) {
    var s = 'nodata';
    list.forEach(function (x) { if (RANK[x] > RANK[s]) s = x; });
    return s;
  }
  function check(id, label, status, display, target, fix, extra) {
    var c = { id: id, label: label, status: status, display: display, target: target, fix: status === 'good' || status === 'nodata' ? '' : fix };
    if (extra) for (var k in extra) c[k] = extra[k];
    // Every limit states its basis (fact-check.md): data, primary, physics,
    // judgement, or provisional ("not yet seen on your car").
    if (!c.basis) c.basis = { t: 'judgement', k: 'app-limit' };
    return c;
  }

  /**
   * Grades a normalized log. opts:
   *   table     current AFM (g/s) values, needed only when the log has g/s but no Hz
   *   baseline  this car's Fuel-quality score Baseline (default 0.49, until the Car
   *               module learns it from cool drives); only moves the timing-cost line
   *   isShakedown  accepted for the Car module; the drive check itself is unchanged
   */
  KTA.analyze = function (log, opts) {
    opts = opts || {};
    var L = KTA.LIMITS, n = log.n, has = log.has, dt = log.dt || 0.1;
    var axis = REF.maf.hz;
    var baseline = isNum(opts.baseline) ? opts.baseline : L.score.baseline;

    // ---- classify samples
    var warm = new Uint8Array(n), wot = new Uint8Array(n), cl = new Uint8Array(n), settled = new Uint8Array(n), sinceStart = new Float64Array(n);
    var thr = has.tps ? log.tps : (has.pedal ? log.pedal : null);
    for (var i = 0; i < n; i++) {
      warm[i] = has.ect ? (log.ect[i] >= 75 ? 1 : 0) : 1;
      var w = false;
      if (thr && isNum(thr[i])) w = thr[i] >= 80;
      else if (has.lamCmd) w = log.lamCmd[i] <= 0.9;
      else if (has.boost) w = log.boost[i] >= 10;
      if (thr && isNum(thr[i]) && thr[i] >= 60 && has.lamCmd && log.lamCmd[i] <= 0.9) w = true;
      // The 1.5T makes 10+ psi with the throttle plate only half open: boost says full load, whatever TPS says.
      if (!w && has.boost && log.boost[i] >= 10 && !(has.tpsCmd && log.tpsCmd[i] < 50)) w = true;
      if (has.rpm && !(log.rpm[i] >= 2000)) w = false;
      wot[i] = w ? 1 : 0;
    }
    // WOT events: contiguous runs (gaps up to 0.3 s bridged), 1 s minimum.
    var events = [], cur = null, gapMax = Math.max(1, Math.round(0.3 / dt));
    for (i = 0; i < n; i++) {
      if (wot[i]) {
        if (cur && i - cur.end <= gapMax) cur.end = i;
        else { if (cur) events.push(cur); cur = { start: i, end: i }; }
      }
    }
    if (cur) events.push(cur);
    events = events.filter(function (e) { return log.t[e.end] - log.t[e.start] >= 1.0; });
    var inEvent = new Uint8Array(n);
    events.forEach(function (e) {
      for (var j = e.start; j <= e.end; j++) {
        inEvent[j] = 1;
        sinceStart[j] = log.t[j] - log.t[e.start];
        var lamOk = !has.lam || log.lam[j] < 0.95;
        settled[j] = sinceStart[j] >= 0.6 && lamOk ? 1 : 0;
      }
      e.t0 = log.t[e.start]; e.t1 = log.t[e.end];
      e.rpm0 = has.rpm ? log.rpm[e.start] : NaN; e.rpm1 = has.rpm ? log.rpm[e.end] : NaN;
      e.duration = round(e.t1 - e.t0, 1);
    });

    var win = Math.max(1, Math.round(0.5 / dt));
    for (i = 0; i < n; i++) {
      var ok = warm[i] && !inEvent[i] && (has.stft || has.ltft);
      if (ok && has.loop) ok = log.loop[i] >= 0.5;
      if (ok && has.lamCmd) ok = Math.abs(log.lamCmd[i] - 1) <= 0.03;
      if (ok && has.lam) ok = log.lam[i] > 0.85 && log.lam[i] < 1.15;
      if (ok && has.rpm) ok = log.rpm[i] >= 550;
      if (ok && thr) { var j0 = Math.max(0, i - win); ok = Math.abs(thr[i] - thr[j0]) <= 6; }
      cl[i] = ok ? 1 : 0;
    }

    // ---- AFM axis position for every sample
    var hz = null, hzNote = '';
    if (has.mafHz) hz = log.mafHz;
    else if (has.mafGs) {
      var tab = opts.table || REF.maf.custom;
      hz = new Float64Array(n);
      for (i = 0; i < n; i++) hz[i] = isNum(log.mafGs[i]) ? invert(axis, tab, log.mafGs[i]) : NaN;
      hzNote = 'Log has AFM g/s but no Hz: Hz estimated from your current AFM table.';
    }

    // ---- closed-loop fuel trims per AFM point
    var trim = new Float64Array(n);
    for (i = 0; i < n; i++) {
      var s = has.stft ? log.stft[i] : 0, l = has.ltft ? log.ltft[i] : 0;
      trim[i] = isNum(s) && isNum(l) ? ((1 + s / 100) * (1 + l / 100) - 1) * 100 : NaN;
      if (Math.abs(trim[i]) > 25) trim[i] = NaN; // glitches and learning resets
    }
    var clSeconds = 0;
    for (i = 0; i < n; i++) if (cl[i] && isNum(trim[i])) clSeconds += dt;
    var clBins = hz ? binByAxis(axis, hz, trim, cl) : null;

    // ---- WOT mixture
    var errPct = new Float64Array(n), errAfr = new Float64Array(n);
    var fpRatio = new Float64Array(n);
    for (i = 0; i < n; i++) {
      errPct[i] = has.lam && has.lamCmd && settled[i] ? (log.lam[i] / log.lamCmd[i] - 1) * 100 : NaN;
      errAfr[i] = has.lam && has.lamCmd && settled[i] ? (log.lam[i] - log.lamCmd[i]) * GAS : NaN;
      fpRatio[i] = has.fp && has.fpTarget && log.fpTarget[i] > 0 ? log.fp[i] / log.fpTarget[i] : NaN;
    }
    var fuelOk = new Uint8Array(n);
    var fpLimited = 0;
    for (i = 0; i < n; i++) {
      fuelOk[i] = settled[i] && (!isNum(fpRatio[i]) || fpRatio[i] >= 0.95) ? 1 : 0;
      if (settled[i] && isNum(fpRatio[i]) && fpRatio[i] < L.fuelPress.good) fpLimited++;
    }
    var wotBins = hz ? binByAxis(axis, hz, errPct, fuelOk) : null;

    var wotRows = REF.wot.rpm.filter(function (r) { return r >= 2000; });
    var byRpm = wotRows.map(function (r) { return { rpm: r, n: 0, cmd: 0, meas: 0, err: 0, lamMax: -Infinity }; });
    if (has.rpm && has.lam && has.lamCmd) {
      for (i = 0; i < n; i++) {
        if (!settled[i] || !isNum(log.lam[i]) || !isNum(log.lamCmd[i])) continue;
        var best = 0, bd = Infinity;
        for (var q = 0; q < wotRows.length; q++) { var d = Math.abs(log.rpm[i] - wotRows[q]); if (d < bd) { bd = d; best = q; } }
        var row = byRpm[best];
        row.n++; row.cmd += log.lamCmd[i]; row.meas += log.lam[i]; row.err += errAfr[i];
        if (log.lam[i] > row.lamMax) row.lamMax = log.lam[i];
      }
    }
    byRpm = byRpm.filter(function (r) { return r.n > 0; }).map(function (r) {
      return { rpm: r.rpm, n: r.n, lamCmd: r.cmd / r.n, lam: r.meas / r.n, errAfr: r.err / r.n, lamMax: r.lamMax };
    });

    // ---- mixture under boost (fact-check §6): only at 12 psi and up, where the map's
    // WOT_Enrich target is its full-load value (11.0 = λ 0.75 on Starter 21; the lower
    // columns ask 11.5 to 14.7 and the load axis was not captured, so no per-cell check).
    // Judged as distance from the map's own full-load target: Watch 0.5 AFR leaner
    // (11.5), Stop 1.0 leaner (12.0) held 0.3 s. The Stop means the commanded fuel is
    // not arriving (pump, AFM preset, injector), not an absolute danger line.
    // Logged AFR is gasoline-scale (λ × 14.7), so no E10 correction.
    var mapWot = Math.min.apply(null, REF.wot.values[REF.wot.values.length - 1]);
    var mixLoad = has.load ? log.load : (has.boost ? log.boost : null);
    var mixCand = new Uint8Array(n), mixCandN = 0;
    if (mixLoad && has.lam) for (i = 0; i < n; i++) if (settled[i] && mixLoad[i] >= L.mixture.boostPsi) { mixCand[i] = 1; mixCandN++; }
    var mixMedAfr = mixCandN ? median(log.lam, mixCand) * GAS : NaN;
    var mixDiff = mixMedAfr - L.mixture.target;
    var mixLean = NaN, mixLeanT = NaN, mixHeldS = 0;
    if (mixCandN) {
      var mlm = maxOf(log.lam, mixCand); mixLean = mlm.value; mixLeanT = mlm.index >= 0 ? log.t[mlm.index] : NaN;
      var runT0 = NaN;
      for (i = 0; i < n; i++) {
        if (mixCand[i] && log.lam[i] * GAS >= L.mixture.target + L.mixture.stopLean) {
          if (!isNum(runT0)) runT0 = log.t[i];
          var runDur = log.t[i] - runT0 + dt;
          if (runDur > mixHeldS) mixHeldS = runDur;
        } else runT0 = NaN;
      }
    }
    var leanStop = mixCandN > 0 && (mixHeldS >= L.mixture.holdS || mixDiff >= L.mixture.stopLean);
    var wotStatus = 'nodata';
    if (mixCandN > 0) wotStatus = leanStop ? 'stop' : (mixDiff >= L.mixture.watchLean ? 'watch' : 'good');

    // ---- summary numbers (vs the AFR command when the log has one: the Full-method page)
    var wotAbsErr = NaN, wotSignedErr = NaN;
    if (has.lam && has.lamCmd) {
      var abs = [], sgn = [];
      for (i = 0; i < n; i++) if (isNum(errAfr[i])) { abs.push(Math.abs(errAfr[i])); sgn.push(errAfr[i]); }
      wotAbsErr = mean(abs); wotSignedErr = mean(sgn);
    }
    var fp05 = quantile(fpRatio, 0.05, settled);

    var overshoot = NaN, overshootRpm = NaN, undershoot = NaN;
    if (has.boost && has.boostTarget) {
      var over = new Float64Array(n), under = [], uMask = new Uint8Array(n), lag = Math.max(1, Math.round(0.3 / dt));
      for (i = 0; i < n; i++) {
        // a falling target (driver lifting) is not overshoot: the turbo is still spinning down
        var holding = i < lag || (log.boostTarget[i] >= log.boostTarget[i - lag] - 0.3 && !(has.tpsCmd && log.tpsCmd[i] < log.tpsCmd[i - lag] - 5));
        // judged in the pull itself (target 12 psi or more): a part-throttle tip-in that briefly
        // reaches 12 psi against a ramping 10 psi target is the ECU's normal boost control
        over[i] = inEvent[i] && log.boostTarget[i] >= 12 && holding ? log.boost[i] - log.boostTarget[i] : NaN;
        if (inEvent[i] && sinceStart[i] >= 1.5 && (!has.rpm || log.rpm[i] >= 3500) && log.boostTarget[i] >= 10) { under.push(log.boostTarget[i] - log.boost[i]); uMask[i] = 1; }
      }
      var mo = sustainedMax(over, null, Math.max(1, Math.round(0.15 / dt)));
      overshoot = mo.value; overshootRpm = mo.index >= 0 && has.rpm ? log.rpm[mo.index] : NaN;
      undershoot = under.length ? mean(under) : NaN;
    }
    var mafMax = has.mafHz ? quantile(log.mafHz, 0.998) : NaN;

    // Samples under load: 4 psi of manifold pressure or more.
    var loadArr = has.load ? log.load : (has.boost ? log.boost : null);
    var underLoad = new Uint8Array(n), underLoadN = 0;
    if (loadArr) for (i = 0; i < n; i++) if (loadArr[i] >= 4) { underLoad[i] = 1; underLoadN++; }

    // Knock. With one retard column and a Knock Control channel (Honda ECU, KTuner or Hondata),
    // a steady few degrees under boost is the retard the ECU schedules from Knock Control, not a
    // knock event: the same load at higher rpm shows 0. Knock Control carries the signal there.
    var knockScheduled = false, knockLoadMed = NaN;
    if (has.knock && has.kControl && log.knockColumns === 1 && underLoadN * dt >= 2) {
      knockLoadMed = median(log.knock, underLoad);
      knockScheduled = knockLoadMed >= 1;
    }
    var knockMax = NaN, knockRpm = NaN, multiCyl = 0;
    if (has.knock) {
      var km = events.length ? maxOf(log.knock, inEvent) : maxOf(log.knock);
      knockMax = km.value; knockRpm = km.index >= 0 && has.rpm ? log.rpm[km.index] : NaN;
      if (has.knockCyl) for (i = 0; i < n; i++) if ((events.length ? inEvent[i] : 1) && log.knockCyl[i] >= 2) multiCyl++;
    }
    var kcStart = NaN, kcEnd = NaN, kcPeak = NaN, kcPeakT = NaN;
    var kcSmooth = null;
    if (has.kControl) {
      kcSmooth = rollingMedian(log.kControl, Math.max(2, Math.round(2.5 / dt)));
      var span = Math.max(1, Math.round(n * 0.15));
      var head = new Uint8Array(n), tail = new Uint8Array(n);
      for (i = 0; i < span; i++) head[i] = 1;
      for (i = n - span; i < n; i++) tail[i] = 1;
      kcStart = median(kcSmooth, head); kcEnd = median(kcSmooth, tail);
      var kpk = maxOf(kcSmooth); kcPeak = kpk.value; kcPeakT = kpk.index >= 0 ? log.t[kpk.index] : NaN;
    }
    // The score the verdict is read from: the peak that was reached at or below
    // score.highRpm. Above that the non-Si ECU raises it on purpose, so a rise up
    // there is kept in the numbers (kcPeak, the episodes) and left out of the fuel
    // and heat verdicts (owner-voices.md §3). Without rpm in the log every sample counts.
    var kcLowMask = null, kcHighMask = null, kcHighSeconds = 0;
    if (kcSmooth && has.rpm) {
      kcLowMask = new Uint8Array(n); kcHighMask = new Uint8Array(n);
      for (i = 0; i < n; i++) {
        var upHere = isNum(log.rpm[i]) && log.rpm[i] > L.score.highRpm;
        kcLowMask[i] = upHere ? 0 : 1;
        kcHighMask[i] = upHere ? 1 : 0;
        if (upHere) kcHighSeconds += log.w[i];
      }
    }
    var kcHighPeak = kcHighMask ? maxOf(kcSmooth, kcHighMask).value : NaN;
    var kcPeakJudged = kcLowMask ? maxOf(kcSmooth, kcLowMask).value : kcPeak;
    if (!isNum(kcPeakJudged)) kcPeakJudged = kcPeak;
    // Said plainly, in the owner's words, when a rise up there is the reason the raw
    // peak is higher than the one the verdict reads (owner-voices.md §3). The app
    // words the same sentence in each language from these numbers.
    function highRpmNote() {
      if (!isNum(kcHighPeak) || !(kcHighPeak > kcPeakJudged)) return '';
      return '. Above ' + F.num(L.score.highRpm, 0) + ' rpm it reached ' + F.num(kcHighPeak, 2) +
        ': the ECU raises the score there on purpose, so those rises do not count toward this line';
    }
    // Fuel-quality score, judged by what it costs under boost (ADR 0001): cost =
    // table x (score - Baseline). Watch from 0.56 (0.7°). "No hard driving" when the
    // drive STARTS at 0.62 (1.3°) and holds it for 60 s or more: a high score that is
    // still there when you set off is fuel or heat, and hard driving waits until it
    // drops. A score earned mid-drive (16:01 climbs 0.49 -> 0.65 through 0.62 but never
    // holds it) keeps its plain Watch and its own cause and action. Stop at 0.80,
    // provisional: never reached on this car.
    // The Stop is read from the whole-drive peak: a Stop protects the engine and
    // must never be silenced by the high-rpm rule. The Watch and "no hard driving"
    // are fuel and heat judgements, so they read kcPeakJudged.
    var kcStatus = 'nodata', kcNoHard = false, timingCost = NaN;
    if (isNum(kcPeakJudged)) {
      if (isNum(kcPeak) && kcPeak >= L.score.stop) kcStatus = 'stop';
      else {
        if (isNum(kcStart) && kcStart >= L.score.noHard) {
          var holdS = 0;
          for (i = 0; i < n && log.t[i] < 120; i++) {
            if (!kcLowMask || kcLowMask[i]) {
              if (isNum(kcSmooth[i]) && kcSmooth[i] >= L.score.noHard) holdS += log.w[i];
            }
          }
          kcNoHard = holdS >= L.score.noHardSecs;
        }
        kcStatus = kcPeakJudged >= L.score.watch ? 'watch' : 'good';
      }
    }
    if (isNum(kcEnd)) timingCost = L.score.tableDeg * (kcEnd - baseline);

    // Intake air: the hottest air a pull breathed. Without a pull, the air under load, then while
    // moving: heat soak at a standstill is shown separately and never graded as a pull.
    var iatMax = NaN, iatWhere = '', iatSoak = NaN;
    if (has.iat) {
      if (events.length) { iatMax = maxOf(log.iat, inEvent).value; iatWhere = 'pull'; }
      else if (underLoadN * dt >= 1) { iatMax = quantile(log.iat, 0.98, underLoad); iatWhere = 'load'; }
      else if (has.vss) {
        var mv = new Uint8Array(n), mvN = 0;
        for (i = 0; i < n; i++) if (log.vss[i] >= 20) { mv[i] = 1; mvN++; }
        if (mvN) { iatMax = quantile(log.iat, 0.98, mv); iatWhere = 'moving'; }
      }
      if (!iatWhere) { iatMax = quantile(log.iat, 0.98); iatWhere = 'log'; }
      if (has.vss) {
        var still = new Uint8Array(n);
        for (i = 0; i < n; i++) still[i] = log.vss[i] < 1 ? 1 : 0;
        iatSoak = quantile(log.iat, 0.95, still);
      }
    }
    var ectMax = has.ect ? quantile(log.ect, 0.995) : NaN;
    var cvtMax = has.cvt ? quantile(log.cvt, 0.995) : NaN;
    var lowBoost = NaN;
    if (has.boost && has.rpm && events.length) {
      var lb = [];
      for (i = 0; i < n; i++) if (inEvent[i] && log.rpm[i] < 3000) lb.push(log.boost[i] - refBoostAt(log.rpm[i]));
      lowBoost = lb.length ? quantile(lb, 0.75) : NaN;
    }

    // ---- log quality gate: flat or missing channels, too-short drive.
    // A channel is flat when its value does not change across the moving part of the
    // drive while engine rpm does (a dead logger channel, not a real reading).
    // Turbo Pressure is also flat when it stays within 0.5 psi while MAP rises above
    // 4 psi. Knock retard is never gated: frozen at 0 is its normal state.
    var movingM = new Uint8Array(n), movingSecs = 0;
    for (i = 0; i < n; i++) {
      var isMoving = has.vss ? log.vss[i] >= 3 : (has.rpm ? log.rpm[i] >= 900 : true);
      if (isMoving) { movingM[i] = 1; movingSecs += log.w[i]; }
    }
    function movingRange(a) {
      var lo = Infinity, hi = -Infinity;
      for (var ri = 0; ri < n; ri++) if (movingM[ri] && isNum(a[ri])) { if (a[ri] < lo) lo = a[ri]; if (a[ri] > hi) hi = a[ri]; }
      return lo === Infinity ? null : hi - lo;
    }
    var rpmRange = has.rpm ? movingRange(log.rpm) : null;
    var rpmMoves = rpmRange != null && rpmRange >= 200;
    function chanFlat(a) {
      if (!a || !rpmMoves) return false;
      var r = movingRange(a);
      return r != null && r < 1e-9;
    }
    var flatCh = {};
    if (chanFlat(log.lam)) flatCh.lam = true;
    if (has.stft || has.ltft) {
      var stF = has.stft ? chanFlat(log.stft) : true, ltF = has.ltft ? chanFlat(log.ltft) : true;
      if (stF && ltF) { if (has.stft) flatCh.stft = true; if (has.ltft) flatCh.ltft = true; }
    }
    if (chanFlat(log.kControl)) flatCh.kControl = true;
    if (chanFlat(log.fp)) flatCh.fp = true;
    if (chanFlat(log.iat)) flatCh.iat = true;
    if (chanFlat(log.ect)) flatCh.ect = true;
    if (chanFlat(log.cvt)) flatCh.cvt = true;
    if (chanFlat(log.boost)) flatCh.boost = true;
    else if (has.boost && has.load && rpmMoves) {
      var bRange = movingRange(log.boost), peakLoad = -Infinity;
      for (var li = 0; li < n; li++) if (movingM[li] && isNum(log.load[li]) && log.load[li] > peakLoad) peakLoad = log.load[li];
      if (bRange != null && bRange <= 0.5 && peakLoad > 4) flatCh.boost = true;
    }
    if (chanFlat(log.boostTarget)) flatCh.boostTarget = true;
    var flatList = Object.keys(flatCh);
    // Safety channels: mixture, fuel trims, Fuel-quality score, fuel pressure.
    // Fuel pressure is judged under boost, so a flat fuel pressure only sinks the
    // verdict when the drive has settled full-throttle samples to judge it by;
    // on a gentle drive its line is Can't tell either way and Block 7 says why.
    var settledN = 0;
    for (i = 0; i < n; i++) if (settled[i]) settledN++;
    var safety = [
      { name: 'mixture', present: has.lam, flat: !!flatCh.lam },
      { name: 'trims', present: has.stft || has.ltft, flat: !!(flatCh.stft || flatCh.ltft) },
      { name: 'score', present: has.kControl, flat: !!flatCh.kControl },
      { name: 'fuelPressure', present: has.fp && has.fpTarget, flat: !!flatCh.fp && settledN > 0 }
    ];
    var missingSafety = safety.filter(function (s) { return !s.present; }).map(function (s) { return s.name; });
    var flatSafety = safety.filter(function (s) { return s.present && s.flat; }).map(function (s) { return s.name; });
    var tooShort = movingSecs < 60;
    var cantTell = null;
    if (tooShort) cantTell = { reason: 'tooShort', movingSeconds: round(movingSecs, 1) };
    else if (missingSafety.length || flatSafety.length) {
      cantTell = {
        reason: 'safetyChannels',
        channels: missingSafety.length ? missingSafety : flatSafety,
        missing: missingSafety.slice(), flat: flatSafety.slice()
      };
    }

    // ---- gates
    var F = KTA.fmt;
    var trimWorst = NaN, trimWorstHz = NaN, binsWithData = 0;
    if (clBins) clBins.forEach(function (b) {
      if (b.weight >= L.minBinWeight && isNum(b.mean)) {
        binsWithData++;
        if (!isNum(trimWorst) || Math.abs(b.mean) > Math.abs(trimWorst)) { trimWorst = b.mean; trimWorstHz = b.hz; }
      }
    });
    if (!clBins && (has.stft || has.ltft)) trimWorst = mean(trim, cl);

    var fuelChecks = [
      check('trims', 'Fuel trims (cruise)', grade(Math.abs(trimWorst), L.trim),
        isNum(trimWorst) ? F.signed(trimWorst, 1, ' %') + (isNum(trimWorstHz) ? ' at ' + F.hz(trimWorstHz) : '') : 'No steady cruise found',
        'Within ±5 %', 'The ECU is correcting fuel against the air meter. Wide trims in every airflow bin mean the wrong air-meter preset or unmetered air after it; trims off in some bins only point at one airflow range. Check what changed since the last Drive.',
        { value: trimWorst, hint: 'trims', basis: { t: 'data', k: 'trims-data' }, data: { value: trimWorst, hz: trimWorstHz } }),
      check('wotAfr', 'Mixture at 12 psi and up', wotStatus,
        mixCandN ? F.num(mixMedAfr, 1) + ' AFR at 12 psi and up, map asks ' + F.num(L.mixture.target, 1) + (mixDiff < -0.05 ? ' (richer: safe)' : '') : 'No time at 12 psi or more',
        'Within 0.5 AFR of the map, never 1.0 leaner held 0.3 s',
        leanStop ? 'Stop pulls: the fuel asked for is not arriving (pump, AFM preset or injector). Fix fuel before any more full-throttle runs.'
          : 'Leaner than the map asks at 12 psi and up: the fuel asked for is not fully arriving, or the air meter over-reads at that flow. Leave the map alone and check fuel supply and the air-meter reading first.',
        { value: mixDiff, hint: 'afr', basis: { t: 'judgement', k: 'mixture-rule' }, data: { measured: mixMedAfr, target: L.mixture.target, diff: mixDiff, leanest: mixLean, leanestT: mixLeanT, leanStop: leanStop, heldSecs: round(mixHeldS, 2), noCmd: !has.lamCmd } }),
      check('fuelPress', 'DI fuel pressure at WOT', grade(fp05, L.fuelPress, true),
        isNum(fp05) ? F.num(fp05 * 100, 0) + ' % of target (worst 5 %)' : 'Not logged',
        '90 % of target or more', 'The high-pressure pump is at its limit. Do not add boost. Check the fuel filter and pump supply.',
        { value: fp05, hint: 'fuelPress', basis: { t: 'judgement', k: 'fuelpress-rule' }, data: { value: fp05 } })
    ];
    var airChecks = [
      check('overshoot', 'Boost overshoot', grade(overshoot, L.overshoot),
        isNum(overshoot) ? F.signed(overshoot, 1, ' psi') + (isNum(overshootRpm) ? ' at ' + F.num(overshootRpm) + ' rpm' : '') : 'Needs boost and boost target',
        'Under +1.5 psi', 'Boost passes the pressure the ECU asked for: the exhaust is delivering air faster than the wastegate control expected, usually a freer exhaust system. Rides the overshoot, then the ECU pulls timing for it. Check the exhaust and the wastegate before anything else.',
        { value: overshoot, hint: 'boost', basis: { t: 'judgement', k: 'overshoot-rule' }, data: { value: overshoot, rpm: overshootRpm } }),
      check('undershoot', 'Boost reaches target', grade(undershoot, L.undershoot),
        !isNum(undershoot) ? 'Needs boost and boost target' : (Math.abs(undershoot) < 0.3 ? 'On target after spool' : F.num(Math.abs(undershoot), 1) + ' psi ' + (undershoot > 0 ? 'below' : 'above') + ' target after spool'),
        'Within 1.5 psi', 'Boost never reaches the pressure the ECU asked for. Warm-only misses point at the wastegate, misses even cold at a boost leak (intercooler couplers, clamps). Check the hoses and the wastegate before anything else.',
        { value: undershoot, hint: 'boost', basis: { t: 'judgement', k: 'undershoot-rule' }, data: { value: undershoot } }),
      check('mafHz', 'AFM sensor headroom', grade(mafMax, L.mafHz),
        isNum(mafMax) ? F.hz(mafMax) + ' peak' : 'AFM Hz not logged',
        'Under 9,500 Hz', 'The air meter is near 10,000 Hz, the end of what it can measure. Above that the ECU cannot know how much air there is, so more boost would be unmeasured fuel. Leave it alone; it is not a fault to chase.',
        { value: mafMax, hint: 'afm', basis: { t: 'judgement', k: 'mafheadroom' }, data: { value: mafMax } })
    ];
    var knockStatus = knockScheduled ? 'good' : grade(knockMax, L.knock);
    if (!knockScheduled && multiCyl * dt >= 0.3 && RANK[knockStatus] < RANK.stop) knockStatus = knockStatus === 'good' ? 'watch' : 'stop';
    var sparkChecks = [
      check('knock', 'Knock retard at WOT', knockStatus,
        knockScheduled ? F.num(knockLoadMed, 1) + '° under boost, scheduled by Knock Control (not knock events)'
          : (isNum(knockMax) ? F.num(knockMax, 1) + '° worst' + (isNum(knockRpm) ? ' at ' + F.num(knockRpm) + ' rpm' : '') + (multiCyl ? ', ' + (multiCyl > 1 ? 'several cylinders together' : 'two cylinders') : '') : 'Knock retard not logged'),
        knockScheduled ? 'Follows Knock Control' : '1° or less', 'Find the cause before adding anything: heat soak, fuel, boost. Rises while lugging are a driving habit; rises under load are fuel or heat. The Fuel-quality score line and the Drive check show where it came from. Never desensitize the knock sensors.',
        { value: knockMax, hint: 'knock', basis: { t: 'judgement', k: 'knock-rule' }, data: { value: knockMax, rpm: knockRpm, multi: multiCyl, scheduled: knockScheduled, loadMedian: knockLoadMed } }),
      check('kControl', 'Fuel-quality score (Knock Control)', kcStatus,
        isNum(kcEnd) ? F.num(kcStart, 2) + ' → ' + F.num(kcEnd, 2) + (kcPeak > Math.max(kcStart, kcEnd) + 0.02 ? ' (peak ' + F.num(kcPeak, 2) + ')' : '')
          + (timingCost >= L.score.showDeg ? '. Under boost your score costs about ' + F.num(timingCost, 1) + '° of timing' : '')
          + (kcNoHard ? '. No hard driving until it drops' : '')
          + (isNum(kcStart) && kcStart > baseline ? '. Starts high after a Flash, ECU reset or new tank: give it 10–15 calm minutes before judging' : '')
          + highRpmNote() : 'Not logged',
        '0.56 or less; no hard driving from 0.62 held; Stop 0.80 (provisional)',
        (kcNoHard ? 'No hard driving until it drops below 0.62: fill RON95 E10 at a busy station, drive the ECO map (18 psi), and give it 10–15 calm minutes.'
          : (isNum(kcEnd) && kcEnd >= L.score.watch ? 'The ECU is pulling timing for fuel or heat. Add nothing; on hot days use ECO (18 psi).' : 'The ECU kept hearing knock during this drive and moved toward its safer timing. Find where it rose (the Drive check shows it) before adding anything.'))
          + highRpmNote(),
        { value: kcEnd, hint: 'kcontrol',
          basis: kcStatus === 'stop'
            ? { t: 'provisional', k: 'score-stop' }
            : { t: 'judgement', k: 'score-rule' },
          data: { start: kcStart, end: kcEnd, peak: kcPeak, peakT: kcPeakT, noHard: kcNoHard, timingCost: timingCost, highStart: isNum(kcStart) && kcStart > baseline, high: isNum(kcEnd) && kcEnd >= L.score.watch,
            highRpmPeak: kcHighPeak, highRpmLimit: L.score.highRpm, judgedPeak: kcPeakJudged, highRpmSeconds: round(kcHighSeconds, 1) } })
    ];
    // Intake heat alone caps at Watch: the score's own limits already catch heat
    // turning into knock, so one danger is never counted twice.
    var iatStatus = grade(iatMax, L.iat);
    if (iatStatus === 'stop') iatStatus = 'watch';
    var heatChecks = [
      check('iat', 'Intake air temp', iatStatus,
        isNum(iatMax) ? F.num(iatMax, 0) + ' °C peak' + (iatWhere === 'pull' ? ' in a pull' : (iatWhere === 'load' ? ' under boost' : (iatWhere === 'moving' ? ' while moving' : ''))) : 'Not logged',
        '50 °C or less', 'Heat-soaked. Cruise 5 minutes to cool before a pull. If it stays high, check the intercooler airflow and the intake heat shield.',
        { value: iatMax, hint: 'iat', basis: { t: 'judgement', k: 'iat-cap' }, data: { value: iatMax, inPull: iatWhere === 'pull', where: iatWhere, soak: iatSoak } }),
      check('ect', 'Coolant temp', grade(ectMax, L.ect),
        isNum(ectMax) ? F.num(ectMax, 0) + ' °C peak' : 'Not logged',
        '100 °C or less', 'Stop logging until coolant is back under 95 °C. Check the radiator, fan and coolant level.',
        { value: ectMax, hint: 'ect', basis: { t: 'provisional', k: 'ect-stop' }, data: { value: ectMax } })
    ];
    // CVT slip (Watch only): revs jumping without speed under boost. Revs up 250 rpm
    // within 0.33 s while speed gains under 1 km/h, with MAP at 8 psi or more, throttle
    // command at 50% or more and speed over 20 km/h. 0 events in the owner's 16 drives
    // (~2,400 boosted rows), so the threshold is unproven against a real slip: the
    // check never says worse than Watch. The g-sensor channel reads 0 on every row
    // and is not used. (The old torque check is gone: the logs carry no torque value,
    // and its 250 Nm figure was a 10th-gen FlashPro warning contradicted by the
    // 11th-gen maps' own +50 lb-ft.)
    var tpsA = has.tpsCmd ? log.tpsCmd : (has.tps ? log.tps : (has.pedal ? log.pedal : null));
    var slipLoad = has.load ? log.load : (has.boost ? log.boost : null);
    var slipEvents = 0, slipAt = NaN;
    var slipReady = has.rpm && has.vss && !!slipLoad && !!tpsA;
    if (slipReady) {
      var slipStep = Math.max(1, Math.round(L.slip.secs / dt));
      for (i = 0; i + slipStep < n; i++) {
        var j = i + slipStep;
        var ld1 = slipLoad[i], ld2 = slipLoad[j];
        if (!(ld1 >= L.slip.mapPsi && ld2 >= L.slip.mapPsi)) continue;
        if (!(tpsA[i] >= L.slip.tps && tpsA[j] >= L.slip.tps)) continue;
        if (!(log.vss[i] > 20 && log.vss[j] > 20)) continue;
        if (!isNum(log.rpm[i]) || !isNum(log.rpm[j]) || !isNum(log.vss[i]) || !isNum(log.vss[j])) continue;
        if (log.rpm[j] - log.rpm[i] > L.slip.rpm && log.vss[j] - log.vss[i] < L.slip.vss) {
          slipEvents++;
          if (!isNum(slipAt)) slipAt = log.t[i];
          i = j;
        }
      }
    }
    var cvtChecks = [
      check('cvtTemp', 'CVT fluid temp', grade(cvtMax, L.cvt),
        isNum(cvtMax) ? F.num(cvtMax, 0) + ' °C peak' : 'Not logged',
        '90 °C or less', 'Stop pulls and cruise gently until under 90 °C. Hot CVT fluid lets the belt slip, and the ECU cuts torque.',
        { value: cvtMax, hint: 'cvt', basis: { t: 'provisional', k: 'cvt-stop' }, data: { value: cvtMax } }),
      check('slip', 'CVT slip (revs without speed)', !slipReady ? 'nodata' : (slipEvents > 0 ? 'watch' : 'good'),
        !slipReady ? 'Needs rpm, speed, boost and throttle' : (slipEvents > 0 ? slipEvents + ' slip event' + (slipEvents === 1 ? '' : 's') + ' under boost' : 'No slip seen under boost'),
        'No slip under boost', 'If the revs jump without speed under boost, the belt may be slipping. Log again with rpm, speed, boost and throttle command; if it repeats, have the CVT fluid and belt checked.',
        { value: slipEvents, hint: 'slip', basis: { t: 'provisional', k: 'slip-watch' }, data: { events: slipEvents, at: slipAt } }),
      check('lowBoost', 'Boost below 3,000 rpm', grade(lowBoost, L.lowRpmBoost),
        isNum(lowBoost) ? F.signed(lowBoost, 1, ' psi') + ' vs reference map' : 'Needs a pull and boost',
        'Within 1.5 psi of the reference map', 'More torque than the reference asks for below 3,000 rpm, which is where the CVT belt is most stressed. Log a pull at the same revs twice to confirm it is real before anyone changes the map.',
        { value: lowBoost, hint: 'cvtbelt', basis: { t: 'judgement', k: 'lowboost-rule' }, data: { value: lowBoost } })
    ];

    // A flat channel poisons only the lines read from it: they become Can't tell
    // instead of grading a dead value. (A flat Safety channel additionally sinks the
    // whole drive; see cantTell above.)
    function flatOut(checks, ids, channel) {
      checks.forEach(function (c) {
        if (ids.indexOf(c.id) >= 0 && c.status !== 'nodata') {
          c.status = 'nodata';
          c.data = c.data || {}; c.data.flat = channel;
        }
      });
    }
    if (flatCh.stft || flatCh.ltft) flatOut(fuelChecks, ['trims'], 'trims');
    if (flatCh.lam) flatOut(fuelChecks, ['wotAfr'], 'mixture');
    if (flatCh.fp && settledN > 0) flatOut(fuelChecks, ['fuelPress'], 'fuelPressure');
    if (flatCh.boost || flatCh.boostTarget) flatOut(airChecks, ['overshoot', 'undershoot'], flatCh.boost ? 'boost' : 'boostTarget');
    if (flatCh.boost) flatOut(cvtChecks, ['lowBoost'], 'boost');
    if (flatCh.kControl) flatOut(sparkChecks, ['kControl'], 'score');
    if (flatCh.iat) flatOut(heatChecks, ['iat'], 'iat');
    if (flatCh.ect) flatOut(heatChecks, ['ect'], 'ect');
    if (flatCh.cvt) flatOut(cvtChecks, ['cvtTemp'], 'cvt');

    var gates = [
      { id: 'fuel', label: 'Fuel', checks: fuelChecks },
      { id: 'air', label: 'Air', checks: airChecks },
      { id: 'spark', label: 'Spark', checks: sparkChecks },
      { id: 'heat', label: 'Heat', checks: heatChecks },
      { id: 'cvt', label: 'CVT', checks: cvtChecks }
    ];
    gates.forEach(function (g) {
      g.status = worst(g.checks.map(function (c) { return c.status; }));
      var lead = g.checks.filter(function (c) { return c.status === g.status; })[0] || g.checks[0];
      g.headline = lead.display;
    });
    var all = [];
    gates.forEach(function (g) { g.checks.forEach(function (c) { all.push(c.status); }); });
    var verdict = worst(all);
    if (cantTell) verdict = 'nodata';

    var readiness = [], readinessCodes = [];
    function ready(code, text, extra) { readiness.push(text); var r = { code: code }; if (extra) for (var k in extra) r[k] = extra[k]; readinessCodes.push(r); }
    if (hzNote) ready('hzEstimated', hzNote);
    if (!hz) ready('noAfm', 'No AFM Hz or g/s column: the app can grade the log but cannot compute AFM corrections.');
    if (clSeconds < 180) ready('shortCruise', 'Only ' + Math.round(clSeconds) + ' s of steady warm cruise. Drive 5-10 minutes at steady speeds for a reliable AFM correction.', { seconds: Math.round(clSeconds) });
    if (!events.length) ready('noPull', 'No full-throttle pull found. Fuel, Air and Spark under load stay unchecked.');
    if (fpLimited * dt > 0.3) ready('fuelLimited', 'Fuel pressure fell under 90 % of target during a pull. Only pull samples with fuel pressure at 95 % of target or more feed the AFM correction: a lean reading there can come from fuel supply, not airflow.');
    if (log.missing.length) ready('missing', 'Not in this log: ' + log.missing.map(function (k) { return channelLabel(k); }).join(', ') + '.', { keys: log.missing.slice() });

    return {
      meta: { rows: n, duration: log.duration, dt: dt, found: log.found, missing: log.missing, units: log.units, notes: log.notes },
      movingSeconds: round(movingSecs, 1),
      tooShort: tooShort,
      cantTell: cantTell,
      flatChannels: flatList.slice(),
      events: events.map(function (e) { return { t0: e.t0, t1: e.t1, duration: e.duration, rpm0: e.rpm0, rpm1: e.rpm1 }; }),
      closedLoopSeconds: round(clSeconds, 1),
      maf: { axis: axis, cl: clBins, wot: wotBins, binsWithData: binsWithData, fpLimitedSeconds: round(fpLimited * dt, 1) },
      wot: { byRpm: byRpm, absErrAfr: wotAbsErr, signedErrAfr: wotSignedErr, leanestLambda: mixLean, leanestT: mixLeanT, fuelPressRatio: fp05 },
      numbers: { overshoot: overshoot, undershoot: undershoot, mafMax: mafMax, knockMax: knockMax, iatMax: iatMax, ectMax: ectMax, cvtMax: cvtMax, lowBoost: lowBoost, kControlStart: kcStart, kControlEnd: kcEnd, kControlPeak: kcPeak, kControlPeakJudged: kcPeakJudged, kControlHighPeak: kcHighPeak, trimWorst: trimWorst, wotMeasuredAfr: mixMedAfr, wotMapAfr: mapWot, iatSoak: iatSoak },
      knockScheduled: knockScheduled,
      gates: gates,
      verdict: verdict,
      verdictLabel: KTA.VERDICT_LABEL[verdict],
      readiness: readiness,
      readinessCodes: readinessCodes
    };
  };

  function channelLabel(key) {
    for (var i = 0; i < CHANNELS.length; i++) if (CHANNELS[i].key === key) return CHANNELS[i].label;
    return key;
  }
  KTA.channelLabel = channelLabel;

