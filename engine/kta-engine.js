  function splitLine(line, delim) {
    var out = [], cur = '', q = false;
    for (var i = 0; i < line.length; i++) {
      var c = line.charAt(i);
      if (q) {
        if (c === '"') { if (line.charAt(i + 1) === '"') { cur += '"'; i++; } else q = false; }
        else cur += c;
      } else if (c === '"') q = true;
      else if (c === delim) { out.push(cur.trim()); cur = ''; }
      else cur += c;
    }
    out.push(cur.trim());
    return out;
  }

  function detectDelimiter(lines) {
    var cands = [',', ';', '\t', '|'], best = ',', bestScore = 0;
    var sample = lines.slice(0, 15);
    cands.forEach(function (d) {
      var counts = sample.map(function (l) { return splitLine(l, d).length; });
      var med = quantile(counts, 0.5);
      var same = counts.filter(function (c) { return c === med; }).length;
      var score = med > 1 ? med * same : 0;
      if (score > bestScore) { bestScore = score; best = d; }
    });
    return best;
  }

  var TEXT_TRUE = /^(closed|cl|on|true|yes|active)/i;
  var TEXT_FALSE = /^(open|ol|off|false|no|inactive)/i;
  function toNum(s, decimalComma) {
    if (s == null) return NaN;
    s = String(s).trim();
    if (!s) return NaN;
    if (decimalComma) s = s.replace(',', '.');
    var m = s.match(/^[-+]?(\d+\.?\d*|\.\d+)(e[-+]?\d+)?/i);
    if (m) return parseFloat(m[0]);
    if (TEXT_TRUE.test(s)) return 1;
    if (TEXT_FALSE.test(s)) return 0;
    return NaN;
  }
  function numericShare(cells, dc) {
    if (!cells.length) return 0;
    var k = 0;
    for (var i = 0; i < cells.length; i++) {
      var c = cells[i];
      if (c !== '' && /^[-+]?(\d|\.\d)/.test(c) && isNum(toNum(c, dc))) k++;
    }
    return k / cells.length;
  }

  /**
   * Parses a datalog export. Tolerates a BOM, metadata lines above the header,
   * a units row under the header, and ; or tab delimiters with decimal commas.
   * Returns { headers, columns (Float64Array per header), rows, delimiter, notes }.
   */
  KTA.parseCSV = function (text) {
    text = String(text == null ? '' : text).replace(/^﻿/, '');
    var lines = text.split(/\r\n|\n|\r/).filter(function (l) { return l.trim().length > 0; });
    if (lines.length < 3) throw new Error('This file has fewer than 3 lines. Export the datalog as CSV and try again.');
    var delim = detectDelimiter(lines);
    var decimalComma = delim !== ',' && /\d,\d/.test(lines.slice(1, 30).join(' '));
    var headerIdx = -1, dataIdx = -1, unitsIdx = -1;
    for (var i = 0; i < Math.min(lines.length - 1, 40) && headerIdx < 0; i++) {
      var a = splitLine(lines[i], delim);
      if (a.length < 3 || numericShare(a, decimalComma) > 0.5) continue;
      for (var j = i + 1; j <= i + 2 && j < lines.length; j++) {
        var b = splitLine(lines[j], delim);
        if (Math.abs(b.length - a.length) > 1) continue;
        if (numericShare(b, decimalComma) >= 0.6) {
          headerIdx = i; dataIdx = j; if (j === i + 2) unitsIdx = i + 1;
          break;
        }
      }
    }
    if (headerIdx < 0) throw new Error('Could not find a header row followed by numbers. Is this a KTuner or Hondata CSV export?');
    var headers = splitLine(lines[headerIdx], delim);
    var notes = [];
    if (unitsIdx > 0) {
      var units = splitLine(lines[unitsIdx], delim);
      headers = headers.map(function (h, k) { return units[k] ? h + ' (' + units[k] + ')' : h; });
    }
    headers = headers.map(function (h, k) { return h || ('Column ' + (k + 1)); });
    var width = headers.length, raw = [], skipped = 0;
    for (var r = dataIdx; r < lines.length; r++) {
      var cells = splitLine(lines[r], delim);
      if (cells.length < Math.ceil(width / 2) || numericShare(cells, decimalComma) < 0.3) { skipped++; continue; }
      raw.push(cells);
    }
    var columns = headers.map(function () { return new Float64Array(raw.length); });
    for (var ri = 0; ri < raw.length; ri++) {
      for (var ci = 0; ci < width; ci++) columns[ci][ri] = toNum(raw[ri][ci], decimalComma);
    }
    if (skipped) notes.push(skipped + ' non-data line(s) skipped.');
    if (headerIdx > 0) notes.push(headerIdx + ' line(s) above the header ignored.');
    return { headers: headers, columns: columns, rows: raw.length, delimiter: delim, decimalComma: decimalComma, notes: notes };
  };

