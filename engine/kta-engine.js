  function matches(ch, h) {
    if (ch.all && !ch.all.every(function (re) { return re.test(h); })) return false;
    if (ch.any && !ch.any.some(function (re) { return re.test(h); })) return false;
    if (ch.none && ch.none.some(function (re) { return re.test(h); })) return false;
    return !!(ch.all || ch.any);
  }

  /** Maps header names to channels. Returns { key: columnIndex | [indices] }. */
  KTA.detectChannels = function (headers, columns) {
    var map = {}, taken = {};
    var normed = headers.map(norm);
    CHANNELS.forEach(function (ch) {
      for (var i = 0; i < normed.length; i++) {
        if (taken[i] || !matches(ch, normed[i])) continue;
        if (ch.multi) { (map[ch.key] = map[ch.key] || []).push(i); taken[i] = true; }
        else { map[ch.key] = i; taken[i] = true; break; }
      }
    });
    // A bare "MAF" column may carry Hz or g/s: decide from the numbers.
    if (columns && map.mafGs != null && map.mafHz == null) {
      var q = quantile(columns[map.mafGs], 0.95);
      if (q > 1500) { map.mafHz = map.mafGs; delete map.mafGs; }
    }
    return map;
  };

